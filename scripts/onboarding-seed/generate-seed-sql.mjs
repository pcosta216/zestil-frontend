#!/usr/bin/env node
// Generates the seed INSERT statements for tbl_onboarding_content from the
// authoring YAML files under content/onboarding/. Not run by the app —
// run manually whenever the YAML content changes, output pasted into a
// migration file.
//
//   node scripts/onboarding-seed/generate-seed-sql.mjs > /tmp/seed.sql
//
// See content/onboarding/*.yaml headers and the plan's "Migration" section
// for the section_id/data shape conventions this script implements.

import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { parse } from "yaml";

const here = path.dirname(fileURLToPath(import.meta.url));
const contentDir = path.join(here, "..", "..", "content", "onboarding");

function loadYaml(name) {
  return parse(readFileSync(path.join(contentDir, name), "utf8"));
}

// Tags an array of {value,label} objects with id_order = (index+1)*10.
function withOrder(list) {
  if (!Array.isArray(list)) throw new Error("withOrder expects an array, got: " + JSON.stringify(list));
  return list.map((opt, i) => ({ id_order: (i + 1) * 10, ...opt }));
}

function sqlLiteral(section_id, dataObj) {
  const json = JSON.stringify(dataObj).replace(/'/g, "''");
  return `insert into public.tbl_onboarding_content (section_id, data) values ('${section_id}', '${json}'::jsonb)\n  on conflict (section_id) do update set data = excluded.data, updated_at = now();`;
}

const nodeCopy = loadYaml("node_copy.yaml");
const cuisine = loadYaml("cuisine_curated_data.yaml");
const intolerance = loadYaml("intolerance_curated_data.yaml");
const pairing = loadYaml("pairing_curated_data.yaml");
const dietMacro = loadYaml("diet_macro_curated_data.yaml");
const allergyMacro = loadYaml("allergy_macro_curated_data.yaml");
const intoleranceMacro = loadYaml("intolerance_macro_curated_data.yaml");

const statements = [];

// --- shared: content:days_of_week ------------------------------------------
statements.push(
  sqlLiteral("content:days_of_week", { options: withOrder(nodeCopy.shared.days_of_week) })
);

// --- node:<id> ---------------------------------------------------------------
for (const [nodeId, raw] of Object.entries(nodeCopy.nodes)) {
  const data = { ...raw };
  if (data.options) data.options = withOrder(data.options);
  if (data.fields) {
    const fields = {};
    for (const [fieldName, fieldDef] of Object.entries(data.fields)) {
      fields[fieldName] = fieldDef.options ? { ...fieldDef, options: withOrder(fieldDef.options) } : { ...fieldDef };
    }
    data.fields = fields;
  }
  // other_capture stays as-is ({prompt, on_invalid_message} — no options to order)
  statements.push(sqlLiteral(`node:${nodeId}`, data));
}

// --- curated:cuisine.sub_cuisines / curated:cuisine.dishes -----------------
function orderedMap(obj) {
  const out = {};
  for (const [key, list] of Object.entries(obj)) out[key] = withOrder(list);
  return out;
}
statements.push(sqlLiteral("curated:cuisine.sub_cuisines", orderedMap(cuisine.sub_cuisines)));
statements.push(sqlLiteral("curated:cuisine.dishes", orderedMap(cuisine.dishes)));

// --- curated:intolerance.common / curated:intolerance.by_allergen ----------
statements.push(sqlLiteral("curated:intolerance.common", { options: withOrder(intolerance.common) }));
statements.push(sqlLiteral("curated:intolerance.by_allergen", orderedMap(intolerance.by_allergen)));

// --- curated:pairing.sides ---------------------------------------------------
// Nested broad_cuisine -> cuisine_narrow -> dish -> {main_label, options}, mirroring
// pairing_curated_data.yaml's own structure exactly (the nesting is organizational only —
// see that file's header) — pushed through as-is except for id_order tagging on each dish's
// options array.
const pairingData = {};
for (const [broadCuisine, narrowMap] of Object.entries(pairing.sides)) {
  const narrowOut = {};
  for (const [narrowCuisine, dishMap] of Object.entries(narrowMap)) {
    const dishOut = {};
    for (const [dish, entry] of Object.entries(dishMap)) {
      dishOut[dish] = { main_label: entry.main_label, options: withOrder(entry.options) };
    }
    narrowOut[narrowCuisine] = dishOut;
  }
  pairingData[broadCuisine] = narrowOut;
}
statements.push(sqlLiteral("curated:pairing.sides", pairingData));

// --- curated:diet_macro.exclusions / allergy_macro.exclusions / intolerance_macro.exclusions
// (no id_order — plain slug arrays) ------------------------------------------
statements.push(sqlLiteral("curated:diet_macro.exclusions", dietMacro.diet_macro_exclusions));
statements.push(sqlLiteral("curated:allergy_macro.exclusions", allergyMacro.allergy_macro_exclusions));
statements.push(sqlLiteral("curated:intolerance_macro.exclusions", intoleranceMacro.intolerance_macro_exclusions));

console.log("-- Generated by scripts/onboarding-seed/generate-seed-sql.mjs — do not hand-edit.");
console.log(`-- ${statements.length} sections.\n`);
console.log(statements.join("\n\n"));
